//! The LAN guard's router-advertisement exemption.
//!
//! `10-startwrt-lan-dhcp-guard.nft` drops router advertisements switched
//! between bridge ports unless the sender's MAC is in its `ra_allow` set. This
//! module renders that set from the DHCP host entries carrying `_allow_ra`.

use std::collections::BTreeSet;
use std::path::Path;

use serde::{Deserialize, Serialize};
use uciedit::openwrt::DhcpHost;

use crate::error::ErrorKind;
use crate::prelude::*;
use crate::utils::DeserializeStdin;
use crate::{CtrlContext, Error};

/// Loaded by fw4 after the guard table it adds to.
const RA_ALLOW_PATH: &str = "/usr/share/nftables.d/ruleset-pre/11-startwrt-lan-ra-allow.nft";

/// Declares the set as well as filling it, so a guard table without one
/// still loads.
fn ra_allow_ruleset(dhcp: &uciedit::Config<'_>) -> String {
    let mut macs = BTreeSet::new();
    for section in &dhcp.sections {
        let Ok(host) = section.get::<DhcpHost>() else {
            continue;
        };
        if host._allow_ra.as_deref() == Some("1") && crate::published_ports::validate_mac(&host.mac)
        {
            macs.insert(host.mac.to_ascii_lowercase());
        }
    }
    let mut out = String::from(
        "# Generated by startwrt from the _allow_ra hosts in /etc/config/dhcp.\n\
         add table bridge startwrt_lan_guard\n\
         add set bridge startwrt_lan_guard ra_allow { type ether_addr; }\n",
    );
    if !macs.is_empty() {
        let macs: Vec<&str> = macs.iter().map(String::as_str).collect();
        out.push_str(&format!(
            "add element bridge startwrt_lan_guard ra_allow {{ {} }}\n",
            macs.join(", ")
        ));
    }
    out
}

/// Re-renders [`RA_ALLOW_PATH`] from the DHCP config on disk. Takes effect on
/// the next firewall reload. Returns whether it wrote.
pub(crate) async fn sync_ra_allow(uci_root: impl AsRef<Path>) -> Result<bool, Error> {
    sync_ra_allow_file(uci_root.as_ref(), Path::new(RA_ALLOW_PATH)).await
}

async fn sync_ra_allow_file(uci_root: &Path, path: &Path) -> Result<bool, Error> {
    crate::published_ports::sync_nft_include(uci_root, path, &["dhcp"], |cfgs| {
        ra_allow_ruleset(&cfgs["dhcp"])
    })
    .await
}

pub(crate) async fn apply_ra_allow(uci_root: impl AsRef<Path>) -> Result<(), Error> {
    apply_ra_allow_file(
        uci_root.as_ref(),
        Path::new(RA_ALLOW_PATH),
        crate::published_ports::reload_firewall_wait,
    )
    .await
}

async fn apply_ra_allow_file<F, Fut>(uci_root: &Path, path: &Path, reload: F) -> Result<(), Error>
where
    F: FnOnce() -> Fut,
    Fut: std::future::Future<Output = Result<(), Error>>,
{
    sync_ra_allow_file(uci_root, path).await?;
    reload().await
}

/// Boot heal: the include lives outside `/etc` and is not kept by sysupgrade.
pub async fn heal_ra_allow(uci_root: impl AsRef<Path>) -> Result<(), Error> {
    if sync_ra_allow(uci_root).await? {
        tracing::info!("lan-guard: router-advertisement allow list rewritten; reloading firewall");
        crate::published_ports::reload_firewall();
    }
    Ok(())
}

#[derive(Debug, Serialize, Deserialize, visit_rs::VisitFields)]
pub struct SetRouterAdvertisementsReq {
    pub mac: String,
    pub allow: bool,
}

rpc_toolkit::reflect_ts!(SetRouterAdvertisementsReq);

/// Sets whether the LAN guard forwards a device's IPv6 router advertisements
/// to the rest of the LAN.
#[instrument(skip_all)]
pub async fn set_router_advertisements<C: CtrlContext>(
    ctx: C,
    DeserializeStdin(req): DeserializeStdin<SetRouterAdvertisementsReq>,
) -> Result<(), Error> {
    if !crate::published_ports::validate_mac(&req.mac) {
        return Err(Error::new(
            eyre!("invalid mac: {}", req.mac),
            ErrorKind::InvalidValue,
        ));
    }
    let mac_upper = req.mac.to_uppercase();
    let allow = req.allow;
    let log_failure = |err: &Error| {
        crate::activity::log(
            "device",
            "router-advertisements",
            false,
            &format!("Failed to update IPv6 router advertisements for {mac_upper}"),
            Some(&err.to_string()),
        );
    };
    let written =
        crate::devices::upsert_dhcp_host(&ctx.uci_root(), &req.mac, move |host, existed| {
            if !existed && !allow {
                return false;
            }
            host._allow_ra = allow.then(|| "1".to_string());
            true
        })
        .await
        .inspect_err(log_failure)?;
    if ctx.effectful() {
        if written {
            crate::devices::reload_dnsmasq();
        }
        apply_ra_allow(ctx.uci_root())
            .await
            .inspect_err(log_failure)?;
    }
    if !written {
        return Ok(());
    }
    crate::activity::log(
        "device",
        "router-advertisements",
        true,
        &format!(
            "{} IPv6 router advertisements from {mac_upper}",
            if allow { "Allowed" } else { "Blocked" }
        ),
        None,
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use uciedit::Arena;

    use super::*;

    const DHCP: &str = "\
config host 'host_aabbccddeeff'
\toption mac 'AA:BB:CC:DD:EE:FF'
\toption _allow_ra '1'

config host 'host_112233445566'
\toption mac '11:22:33:44:55:66'
\toption _allow_dns_inject '1'

config host 'host_bad'
\toption mac 'not-a-mac'
\toption _allow_ra '1'
";

    #[tokio::test]
    async fn renders_only_allowed_valid_macs() {
        let dir = tempfile::tempdir().unwrap();
        tokio::fs::write(dir.path().join("dhcp"), DHCP)
            .await
            .unwrap();
        let include = dir.path().join("ruleset-pre/ra.nft");

        assert!(sync_ra_allow_file(dir.path(), &include).await.unwrap());
        assert!(!sync_ra_allow_file(dir.path(), &include).await.unwrap());
        let rendered = tokio::fs::read_to_string(&include).await.unwrap();
        assert!(rendered
            .ends_with("add element bridge startwrt_lan_guard ra_allow { aa:bb:cc:dd:ee:ff }\n"));
        assert!(!rendered.contains("11:22:33"));
        assert!(!rendered.contains("not-a-mac"));
    }

    #[tokio::test]
    async fn retries_activation_when_include_already_matches() {
        let dir = tempfile::tempdir().unwrap();
        tokio::fs::write(dir.path().join("dhcp"), DHCP)
            .await
            .unwrap();
        let include = dir.path().join("ruleset-pre/ra.nft");
        let attempts = std::cell::Cell::new(0);

        let result = apply_ra_allow_file(dir.path(), &include, || async {
            attempts.set(attempts.get() + 1);
            Err(Error::new(eyre!("activation failed"), ErrorKind::Network))
        })
        .await;
        assert!(result.is_err());
        assert!(include.exists());
        assert_eq!(attempts.get(), 1);

        apply_ra_allow_file(dir.path(), &include, || async {
            attempts.set(attempts.get() + 1);
            Ok(())
        })
        .await
        .unwrap();
        assert_eq!(attempts.get(), 2);
    }

    #[test]
    fn empty_allow_list_still_declares_the_set() {
        let arena = Arena::new();
        let dhcp = uciedit::Config::parse_str(&arena, "").unwrap();
        let rendered = ra_allow_ruleset(&dhcp);
        assert!(rendered.contains("add set bridge startwrt_lan_guard ra_allow"));
        assert!(!rendered.contains("add element"));
    }
}
