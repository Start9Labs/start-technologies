#!/usr/bin/env bash
# Regenerates the K1 vendor kernel patch: the vendor tree at VENDOR_REF as a diff
# against the mainline release the image builds from (LINUX_VERSION-6.18 in
# openwrt-overlay/target/linux/generic/kernel-6.18).
#
# Usage: projects/start-wrt/build/gen-kernel-patch.sh
set -euo pipefail

VENDOR_URL=https://gitlab.com/jmontleon/kernel-ark.git
VENDOR_REF=b9f88a74901a71a6bdf666c90d86ee7027f56b7d
STABLE_URL=https://git.kernel.org/pub/scm/linux/kernel/git/stable/linux.git

# Fedora ARK packaging and patches the vendor tree carries beside the K1 work.
# Each path goes back to its mainline content.
FEDORA=(
	.gitignore
	.gitlab-ci.yml
	Documentation/hid/intel-ish-hid.rst
	Makefile
	Makefile.rhelver
	arch/arm/Kconfig
	arch/arm64/Kconfig
	arch/arm64/kernel/setup.c
	arch/s390/include/asm/ipl.h
	arch/s390/kernel/ipl.c
	arch/s390/kernel/setup.c
	arch/x86/kernel/setup.c
	crypto/sig.c
	crypto/testmgr.c
	drivers/acpi/apei/hest.c
	drivers/acpi/irq.c
	drivers/acpi/scan.c
	drivers/ata/libahci.c
	drivers/char/ipmi/ipmi_dmi.c
	drivers/char/ipmi/ipmi_msghandler.c
	drivers/firmware/efi/Makefile
	drivers/firmware/efi/efi.c
	drivers/firmware/efi/libstub/fdt.c
	drivers/firmware/efi/libstub/secureboot.c
	drivers/firmware/efi/secureboot.c
	drivers/hid/hid-rmi.c
	drivers/hid/intel-ish-hid/ishtp/loader.c
	drivers/hwtracing/coresight/coresight-etm4x-core.c
	drivers/input/rmi4/rmi_driver.c
	drivers/iommu/iommu.c
	drivers/media/i2c/ov02c10.c
	drivers/media/pci/intel/Kconfig
	drivers/media/pci/intel/ipu-bridge.c
	drivers/pci/quirks.c
	drivers/scsi/sd.c
	drivers/usb/core/hub.c
	include/linux/efi.h
	include/linux/lsm_hook_defs.h
	include/linux/module.h
	include/linux/rmi.h
	include/linux/security.h
	kernel/module/main.c
	kernel/module/signing.c
	makefile
	redhat
	scripts/Makefile.lib
	scripts/mod/modpost.c
	scripts/tags.sh
	security/integrity/platform_certs/load_uefi.c
	security/lockdown/Kconfig
	security/lockdown/lockdown.c
	tools/testing/selftests/bpf/Makefile
	tools/testing/selftests/bpf/prog_tests/ksyms_btf.c
)

# Vendor drivers no StartWRT image builds. Each goes with the parent Kconfig
# `source` line and Makefile `obj-` line that name it.
EXCLUDE=(
	drivers/gpu/drm/img-rogue
	drivers/gpu/drm/nulldisp
	drivers/media/platform/spacemit
	drivers/net/wireless/realtek/rtl8852be
	drivers/net/wireless/realtek/rtl8852bs
)

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KERNEL_FILE="$PROJECT_DIR/openwrt-overlay/target/linux/generic/kernel-6.18"
OUT="$PROJECT_DIR/openwrt-overlay/target/linux/spacemit/patches-6.18/0000-spacemit-k1-vendor-kernel.patch"

sublevel="$(sed -n 's/^LINUX_VERSION-6\.18 = \.\([0-9]*\)$/\1/p' "$KERNEL_FILE")"
[ -n "$sublevel" ] || { echo "no LINUX_VERSION-6.18 in $KERNEL_FILE" >&2; exit 1; }
BASE_TAG="v6.18.$sublevel"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
git init -q "$WORK"
cd "$WORK"

echo "==> Fetching $BASE_TAG and $VENDOR_REF (shallow)..."
git fetch -q --depth 1 "$STABLE_URL" tag "$BASE_TAG"
git fetch -q --depth 1 "$VENDOR_URL" "$VENDOR_REF"
git checkout -q --detach "$VENDOR_REF"

vendor_sublevel="$(sed -n 's/^SUBLEVEL = //p' Makefile)"
[ "$vendor_sublevel" = "$sublevel" ] || {
	echo "vendor tree is 6.18.$vendor_sublevel, kernel-6.18 pins 6.18.$sublevel" >&2
	exit 1
}

for path in "${FEDORA[@]}"; do
	if git cat-file -e "$BASE_TAG:$path" 2>/dev/null; then
		git checkout -q "$BASE_TAG" -- "$path"
	else
		git rm -rq "$path"
	fi
done

for dir in "${EXCLUDE[@]}"; do
	parent="$(dirname "$dir")"
	name="$(basename "$dir")"
	git rm -rq "$dir"
	for edit in "Kconfig|^source \"$dir/Kconfig\"\$" "Makefile|^obj-.*[[:space:]]$name/\$"; do
		file="$parent/${edit%%|*}"
		pattern="${edit#*|}"
		[ "$(grep -c -- "$pattern" "$file")" = 1 ] || {
			echo "expected one reference to $dir in $file" >&2
			exit 1
		}
		sed -i "\\|$pattern|d" "$file"
	done
done
for dir in "${EXCLUDE[@]}"; do
	if git grep -n -e "$dir/" -- '*Kconfig*' '*Makefile*' '*Kbuild*' >&2; then
		echo "$dir is still referenced" >&2
		exit 1
	fi
done
git add -A

if git diff --cached "$BASE_TAG" | grep -inE '^\+.*(redhat|rhel)' >&2; then
	echo "Fedora changes outside FEDORA; add their paths to it" >&2
	exit 1
fi

if [ -f "$OUT" ]; then
	git diff --cached --name-only "$BASE_TAG" | sort > "$WORK/new-paths"
	sed -n 's|^diff --git a/\([^ ]*\) .*|\1|p' "$OUT" | sort > "$WORK/old-paths"
	added="$(comm -23 "$WORK/new-paths" "$WORK/old-paths")"
	if [ -n "$added" ]; then
		echo "==> Paths new to the patch; review each for Fedora-only changes:"
		printf '    %s\n' $added
	fi
fi

{
	cat <<EOF
Subject: spacemit: SpaceMiT K1 vendor kernel

The $VENDOR_URL tree at $VENDOR_REF,
as a diff against mainline $BASE_TAG, without its Fedora packaging and
patches or these vendor drivers:

$(printf '  %s\n' "${EXCLUDE[@]}")

Generated by projects/start-wrt/build/gen-kernel-patch.sh; do not edit.

EOF
	git -c core.abbrev=12 -c diff.renames=false diff --cached --no-color --no-ext-diff \
		--no-textconv --diff-algorithm=myers "$BASE_TAG"
} > "$OUT"

echo "==> Wrote $OUT ($(wc -c < "$OUT") bytes)"
